import type { WeaponDef, WeaponType } from "../types";
import { defaultWeaponTalentId, weaponTalentById } from "./weapon-talents";

function he(
  id: string,
  name: string,
  type: WeaponType,
  rpm: number,
  mag: number,
  talentId?: string,
): WeaponDef {
  const talent = weaponTalentById(talentId ?? defaultWeaponTalentId(type));
  return {
    id,
    name,
    type,
    quality: "high-end",
    rpm,
    mag,
    talent: talent?.name ?? "Optimist",
    talentDesc: talent?.description ?? "Weapon damage is increased by 3% for every 10% magazine missing.",
  };
}

